// continue
for (let i = 10; i <= 20; i++) {
    if (i === 13) {
        continue;
    } else {
        console.log("The number is: " + i)
    }
}

// break
for (let i = 10; i <= 20; i++) {
    if (i === 13) {
        break;
    } else {
        console.log("The number is: " + i)
    }
}